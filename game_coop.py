#!/usr/bin/env python
# game_coop.py — Round 7 two-owner co-op game: file handshake, one page.
#
# Two owners share ONE browser page and take strict alternating turns:
#   avery — played by this script (the assistant side)
#   sam   — played by YOU (the user side). On a Sam turn the script writes
#           coop_state.json, you answer with coop_response.json, and the
#           script plays your move in the app. One page only: the mock
#           stores are in-process statics, so a second tab/context cannot
#           see a minted invite (sign out/in via the app button instead).
#
# Personas (password `demo123`, emails `name@demo.test`, none reserved):
#   Avery's team - invites generated by Avery, accepted on Sam's turns:
#     casey associate, quinn staff, riley client
#   Sam's team   - invites generated by Sam, accepted on Avery's turns:
#     blake associate, dana staff, erin client
#
# Handshake files (repo root, gitignored):
#   coop_state.json     {turn, of, player, title, situation, options,
#                        default, status: waiting|playing|done, decision}
#   coop_response.json  {"turn": <same>, "decision": "<option or free text>"}
#   The script polls for the response, deletes it, and plays your move.
#
# Usage:
#   python game_coop.py              # headed, waits for coop_response.json
#   python game_coop.py --auto       # unattended: Sam's turns auto-answer
#   python game_coop.py --headless   # no visible window (self-test)
#
# Rules honored: NEVER reload or close the window (a reload wipes the mock
# stores this run created), sign-out only through the app's Sign Out.
# Marketplace: Avery discovers Sam and sends the Associate Request, Sam
# accepts, Avery records a payment and Sam's ledger takes the commission.
# The REVERSE leg is deliberately NOT played — once the first collab is
# active, yoga is a covered job for Sam, so Rule 4 of the marketplace hides
# every yoga business (Avery included) from his results. Turn 20 asserts
# that block instead of pretending a second collab is possible.
# Recap -> game_recap_*.md (via game_driver.write_recap).

