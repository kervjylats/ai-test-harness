def _write_state(**kw):
    kw.setdefault("turn", _ST["turn"])
    kw.setdefault("of", _ST["of"])
    kw.setdefault("player", _CUR.get("player"))
    kw.setdefault("title", _CUR.get("title"))
    kw.setdefault("situation", _CUR.get("situation"))
    kw.setdefault("options", _CUR.get("options"))
    kw.setdefault("default", _CUR.get("default"))
    kw.setdefault("decision", _CUR.get("decision"))
    kw.setdefault("status", "playing")
    kw["updated"] = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    with open(STATE_FILE, "w", encoding="utf-8") as fh:
        json.dump(kw, fh, indent=2)


def begin_turn(player, title, situation, options=None, default="go"):
    """Announce a turn, persist it, and (for Sam) wait for the handshake."""
    _ST["turn"] += 1
    n = _ST["turn"]
    opts = list(options or ["go"])
    gd.banner(f"TURN {n}/{_ST['of']} — {player.upper()}: {title}")
    print(situation, flush=True)
    _CUR.update({"player": player, "title": title, "situation": situation,
                 "options": opts, "default": default, "decision": None})
    decision = None
    if player == "sam":
        _write_state(status="waiting")
        if _ST["auto"]:
            decision = default
            print(f"  (auto) decision: {decision}", flush=True)
        else:
            print(f"  YOUR MOVE: save {RESPONSE_FILE} next to this script "
                  f'as {{"turn": {n}, "decision": "<{opts[0]}>"}}',
                  flush=True)
            decision = _poll_response(n, default)
        _CUR["decision"] = decision
        gd.DECISIONS.append({"gate": n, "persona": SAM["email"],
                             "prompt": title, "decision": decision})
        print(f"  -> Sam decides: {decision}", flush=True)
        _write_state(status="playing")
    else:
        _write_state(status="playing")
    return decision


def _poll_response(turn, default):
    """Block until coop_response.json for this turn exists; delete it."""
    hinted = False
    while True:
        if os.path.exists(RESPONSE_FILE):
            try:
                with open(RESPONSE_FILE, encoding="utf-8") as fh:
                    resp = json.load(fh)
            except (json.JSONDecodeError, OSError):
                resp = None  # mid-save or junk: keep polling
            if resp is not None:
                if int(resp.get("turn", -1)) == turn:
                    os.remove(RESPONSE_FILE)
                    return str(resp.get("decision", "")).strip() or default
                print(f"  stale response for turn {resp.get('turn')} "
                      f"(want {turn}) — removed", flush=True)
                os.remove(RESPONSE_FILE)
        if not hinted:
            print(f"  waiting for {RESPONSE_FILE} ... (Ctrl+C aborts)",
                  flush=True)
            hinted = True
        time.sleep(1.0)


def end_turn(page, title, ok, note="", screenshot=None):
    gd.scene(page, title, ok, note, screenshot=screenshot)
    _write_state(status="done", result="pass" if ok else "fail", note=note)


def skip_cascade(reason, until_turn=25):
    """A gate declined the marketplace path: honestly skip the rest of the
    plan and jump to the closing turns."""
    for n in range(_ST["turn"] + 1, until_turn + 1):
        gd.skip_scene(f"planned turn {n} (cascade)", reason)
    _ST["turn"] = until_turn
    _write_state(status="cascade", note=reason)


