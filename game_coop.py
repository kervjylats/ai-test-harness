def ensure_slot(page, title, want=True):
    """Idempotent: make the switch named `title` read `want`, only touching it
    when it disagrees.

    mt.toggle_slot() is a FLIP, not a setter -- tapping an already-correct
    switch turns it OFF, and switching Discoverable off also wipes every
    open slot (marketplace_notifier.dart). So never call it blind; always
    read the state first.

    Addressing is by label (mt.switch_state), never by position: the card
    now carries an extra same-job toggle and lazily built rows, so index
    math clicks the wrong switch. Slot rows are also LOCKED while
    Discoverable is off, so Discoverable must come first.
    """
    sw = mt.find_switch(page, title)
    if sw is None:
        print(f"    slot {title!r}: NOT FOUND {mt.card_titles(page)}")
        return False
    if sw["checked"] == ("true" if want else "false"):
        print(f"    slot {title!r}: already {want} (no tap)")
        return True
    if sw["disabled"]:
        print(f"    slot {title!r}: LOCKED, cannot set {want} "
              f"(turn Discoverable on first?)")
        return False
    mt.toggle_slot(page, title)
    sw = mt.find_switch(page, title)
    ok = sw is not None and sw["checked"] == ("true" if want else "false")
    print(f"    slot {title!r}: -> {want} ({'OK' if ok else 'CHECK'})")
    return ok


def send_marketplace_request(page, target_business, slot):
    """Discover a tile, open its collab slot, pick the category chip, then
    send + confirm.

    Two things the app insists on that Round 7 got wrong:
      1. 'Send $partnerTerm Request' is DISABLED until a category chip is
         selected (marketplace_profile_card.dart) -- clicking it directly is
         a no-op.
      2. The label is built from config terminology ('Send Associate
         Request'), not a hardcoded string, so match it by prefix.
    """
    mt.scroll_down(page, steps=6)
    has_tile = mt.has(page, [target_business])
    sent = False
    chip = False
    if has_tile:
        mt.click_contains(page, target_business, wait=3000)
        mt.enable_flutter_acc(page)
        if mt.has(page, ["Open Collab Slots"]):
            chip = mt.click_exact(page, slot, wait=1500)
            mt.enable_flutter_acc(page)
        hit = mt.click_btn_prefix(page, "Send")
        page.wait_for_timeout(2500)
        mt.enable_flutter_acc(page)
        if mt.has(page, ["Confirm Request"]):
            mt.fill_first_input(page, "Would love to collab.")
            mt.click_exact(page, "Confirm Request", wait=6000)
            page.wait_for_timeout(3500)
            mt.enable_flutter_acc(page)
            sent = mt.has(page, ["Request sent"])
        sent = sent or bool(hit and mt.has(page, ["Pending"]))
    page.keyboard.press("Escape")
    page.wait_for_timeout(1200)
    return has_tile, chip and sent


def accept_collab_request(page, sender_business):
    """Marketplace -> Received Requests -> Accept -> Confirm Collab."""
    mt.go_marketplace(page)
    mt.scroll_down(page, steps=6)
    got = mt.has_all(page, ["Received Requests", sender_business])
    confirmed = False
    if got:
        mt.click_exact(page, "Accept", wait=6000)
        page.wait_for_timeout(3000)
        mt.enable_flutter_acc(page)
        # _ConfigureCommissionDialog opens with prefilled defaults; key on the
        # confirm button rather than the dialog title so a renamed heading
        # cannot stall the flow.
        if mt.has(page, ["Confirm Collab"]):
            mt.click_exact(page, "Confirm Collab", wait=6000)
            page.wait_for_timeout(3700)
            mt.enable_flutter_acc(page)
            # Snackbar 'Collab with <name> is active' or, failing that, the
            # request rows being gone.
            confirmed = mt.has(page, ["is active"]) or not mt.has(
                page, ["Accept", "Decline", "Confirm Collab"])
    return got, confirmed


def approve_pending(page, expect_chip="1 Pending"):
    """Dashboard pending chip -> Approve -> agreement Active."""
    pending = mt.has(page, [expect_chip])
    approved = False
    if pending:
        mt.click_contains(page, expect_chip, wait=4000)
        page.wait_for_timeout(2500)
        mt.enable_flutter_acc(page)
        if mt.has(page, ["Approve"]):
            mt.click_exact(page, "Approve", wait=6000)
            page.wait_for_timeout(3500)
            mt.enable_flutter_acc(page)
            page.evaluate("() => { window.location.hash = '#/owner'; }")
            page.wait_for_timeout(3000)
            mt.enable_flutter_acc(page)
            approved = not mt.has(page, [expect_chip])
    return pending, approved


def record_payment(page, amount, chip, partner_business):
    """Agreement detail -> Record payment -> then Revenue -> Mark Paid.
    Returns (dialog_ok, closed, revenue_ok, paid, payout) detail."""
    mt.go_home(page)
    opened = mt.click_contains(page, chip, wait=4000)
    page.wait_for_timeout(2500)
    mt.enable_flutter_acc(page)
    if not mt.has(page, ["Record payment"]) and partner_business:
        mt.click_contains(page, partner_business, wait=3000)
        page.wait_for_timeout(2500)
        mt.enable_flutter_acc(page)
    detail = mt.has_after_scroll(page, ["Record payment", "End Agreement"])
    dialog_ok = False
    if detail:
        mt.click_exact(page, "Record payment", wait=6000)
        page.wait_for_timeout(2500)
        mt.enable_flutter_acc(page)
        labels = mt.input_labels(page)
        dialog_ok = (mt.has(page, ["Confirm Payment", "Payment method"])
                     and any(a.startswith("Amount") for a in labels))
    closed = False
    if dialog_ok:
        mt.fill_by_label_prefix(page, "Amount", str(amount))
        mt.click_exact(page, "Confirm Payment", wait=1200)
        page.wait_for_timeout(3500)
        mt.enable_flutter_acc(page)
        closed = mt.until_absent(page, ["Confirm Payment"], 8000)
        if mt.has(page, ["Confirm Payment"]):
            mt.click_exact(page, "Cancel", wait=3000)
    mt.go_home(page)
    mt.find_and_click(page, "Revenue", timeout=6000)
    page.wait_for_timeout(3000)
    mt.enable_flutter_acc(page)
    revenue_ok = mt.has_after_scroll(page, ["Session payment", "Mark Paid"])
    paid = payout = False
    if revenue_ok:
        mt.click_exact(page, "Mark Paid", wait=6000)
        page.wait_for_timeout(3500)
        mt.enable_flutter_acc(page)
        paid = not mt.has(page, ["Mark Paid"])
        payout = mt.has_after_scroll(
            page, [f"Commission payout to {partner_business}"])
    return dict(opened=bool(opened), detail=detail, dialog=dialog_ok,
                closed=closed, revenue=revenue_ok, paid=paid, payout=payout)


